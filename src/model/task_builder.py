            # ИМЯ ИЗ 1С ИДЁТ ПЕРВЫМ (бой 08.10.2026). Модель адресовала задачу именем из
            # прайса «8/32 Классик», а в 1С коллекция — «Classic 8-32V»: исполнитель не нашёл

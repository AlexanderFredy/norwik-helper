class TaskBuilderTools:
    """Исполнитель инструментов одного прогона формирования задач."""

    def __init__(self, content: bytes, filename: str, onec=None,
                 elsewhere: dict | None = None, scope=None,
                 known_columns: dict | None = None,
                 only_sheets: str | None = None,
                 only_marks: list | None = None,
                 discounts: dict | None = None,
                 currency: dict | None = None,
                 logos: dict | None = None,
                 catalogue=None) -> None:
        self._content = content
        self._filename = filename
        self._onec = onec
        # КАТЕГОРИИ (`/categories`) — что вообще разрешено трогать. Пустой список значит
        # «ограничений нет», а не наоборот. Исполнитель задач их получал давно, сборщик —
        # нет, и это стоило задачи «завести подложку» по прайсу Linderwood: вид товара в
        # список не входит, работы по нему нет вовсе (бой 28.09.2026).
        self._scope = [str(c).strip() for c in (scope or ()) if str(c).strip()]
        # ЗАПОМНЕННАЯ ТРАКТОВКА КОЛОНОК: лист → {article, purchase, rrc}. Ключ у памяти —
        # СИГНАТУРА формата, а не файл, поэтому выбор, сделанный админом однажды, держится
        # и на следующем прайсе того же поставщика. Модельный поток её раньше не читал
        # вовсе, и у Линдервуда с двумя колонками закупки (самовывоз и с доставкой) агент
        # выбирал заново каждую пересборку (вопрос админа 28.09.2026).
        self._known_columns = {str(k): dict(v) for k, v in (known_columns or {}).items()}
        # УКАЗАНИЕ АДМИНА: какие листы разбирать. Хранится у сигнатуры формата, то есть
        # действует и на следующий файл того же поставщика. У FLOOR SERVICE четырнадцать
        # листов, по делу два-три, и каждый лишний стоит и токенов, и кругов цикла.
        #
        # `None` И ПУСТАЯ СТРОКА — РАЗНОЕ, и путать их нельзя:
        #   None — выбором листов никто не управляет (так зовут из тестов и из кода, которому
        #          до листов дела нет), разбираем всё;
        #   ""   — выбор ЕСТЬ и он пуст: админ не отметил ни одного листа, и разбирать нечего
        #          (решение админа 02.10.2026).
        # Боевой путь всегда передаёт строку: `main.py` читает её у сигнатуры, и «не
        # отмечено» приезжает сюда пустой строкой, а не отсутствием параметра.
        self._only = (None if only_sheets is None
                      else [n.strip() for n in only_sheets.split(",") if n.strip()])
        # ВТОРОЕ УКАЗАНИЕ АДМИНА: какие БРЕНДЫ разбирать внутри листа (решение 03.10.2026).
        # Выбор листов не помогает прайсу, у которого лист один: у «Остатков» одна вкладка
        # на 1286 строк и 23 бренда — 88 тыс. токенов за полный разбор, причём 13 брендов из
        # 23 в справочнике 1С отсутствуют вовсе, то есть больше половины файла не работа, а
        # мусор. К разбору уходит ПЕРЕСЕЧЕНИЕ отмеченных листов и отмеченных брендов.
        #
        # `None` и пустой список — РАЗНОЕ, ровно как у листов:
        #   None — брендами никто не управляет (колонки бренда в формате нет), разбираем всё;
        #   []   — выбор ЕСТЬ и он пуст: ни один бренд не отмечен, разбирать нечего.
        self._marks = (None if only_marks is None
                       else [str(n).strip() for n in only_marks if str(n).strip()])
        # УСЛОВИЯ ПЕРЕСЧЁТА ЦЕН для прайсов без закупки (решение админа 03.10.2026):
        # скидка дилера от розницы — СВОЯ у каждого бренда, курс валюты — у прайса.
        # Ключи скидок нормализованы (`scope.normalize`), как и имена брендов.
        self._discounts = {normalize(k): v for k, v in (discounts or {}).items()
                           if normalize(k)}
        # ВАЛЮТА ПРАЙСА С КУРСОМ: {"code", "name", "rate"}. Пусто — рубль, как раньше.
        self._currency = dict(currency or {})
        # Что в итоге разобрали и что пропустили — для отчёта админу. Считает КОД: он
        # знает это точно, а пересказ модели однажды разойдётся с правдой.
        self.parsed_sheets: list[str] = []
        self.skipped_sheets: list[str] = []
        self.unknown_sheets: list[str] = []
        # То же по брендам: что оставили, что отсекли, и сколько строк из скольких уцелело.
        # Число строк важно само по себе — им измеряется и экономия, и правдоподобие: если
        # уцелело ноль, разбирать нечего, и молчать об этом нельзя.
        self.parsed_marks: list[str] = []
        self.skipped_marks: list[str] = []
        self.kept_rows = 0
        self.whole_rows = 0
        # Знаков в отмеченном — по ним считается оценка в токенах для предохранителя.
        self.picked_chars = 0
        # Бренд → сколько у него товарных строк. Нужен отчёту при отказе по объёму: назвать
        # «слишком много», не сказав, кто именно крупный, значит заставить админа гадать.
        self.brand_sizes: dict[str, int] = {}
        # Чем бренд обозначен в каждом листе: колонкой, разделителем или картинкой. Идёт в
        # отчёт админу: по пустому списку брендов он должен понимать, откуда они берутся.
        self.brand_modes: dict[str, str] = {}
        # Строка картинки → бренд на ней, по листам. Код знает, ГДЕ баннер (`parser.
        # image_anchor_rows`), а ЧЕЙ на нём логотип — читает модель один раз на логотип и
        # помнит по его хешу. Сюда это приходит ГОТОВЫМ: внутри инструментов спрашивать
        # модель неоткуда, да и платить за это каждому прогону незачем.
        self._logos = dict(logos or {})
        # СПРАВОЧНИК МАРОК 1С — внешнее доказательство для двух способов детекции: разделитель,
        # совпавший с именем настоящей марки («CLASSEN» у Стройиндустрии), и бренд в имени
        # листа («Ассортимент CLASSEN»). Без справочника оба молчат: выдумывать бренды,
        # не сверяясь ни с чем, нельзя — по ним режут файл и пишут цены.
        self._catalogue = list(catalogue or [])
        # Листы, которые агент РЕАЛЬНО прочитал. «Проанализировал» — это про них, а не про
        # те, что ему предложили: лист можно было не открыть вовсе, и админ должен видеть
        # разницу между «исключил я» и «агент сам не стал смотреть».
        self.read_sheets: list[str] = []
        # Почему разбирать нечего: «листы не отмечены» либо «ни один отмеченный не найден».
        # Пусто — разбирать есть что. Это НЕ ошибка файла: файл цел, просто выбор не сделан
        # или устарел, и сообщения тут нужны разные.
        self.pick_problem = ""
        # Артикул → где его видели у ДРУГИХ поставщиков (`storage/sightings.py`). Снимок
        # берётся один раз перед ходом: спрашивать базу из синхронного кода инструментов
        # неоткуда, а таблица мала.
        self._elsewhere = elsewhere or {}
        # Что этот прайс показал: артикул → коллекция, как она названа В ПРАЙСЕ. Ляжет в
        # тот же журнал после прогона — из него и узнает о коллекции следующий прайс.
        self.seen_articles: dict[str, str] = {}
        # Что этот поставщик просит: артикул → {purchase, rrc}. Ложится в тот же журнал
        # и потом решает, чью цену писать в 1С (§6.4): наименьшую среди свежих.
        self.seen_prices: dict[str, dict] = {}
        # Коллекция (нормализованно) → позиции, которые в 1С УЖЕ ЕСТЬ, но вне живой папки:
        # чаще всего снятые. Заводить их заново нельзя — это дубль.
        self._revivals: dict[str, list] = {}
        # (код марки, имя коллекции в ПРАЙСЕ) → как она зовётся В 1С, по итогу сверки.
        # Адрес задачи обязан нести имя из 1С: исполнитель ищет коллекцию именно по нему
        # (бой 08.10.2026: «8/32 Классик» против «Classic 8-32V»).
        self._names_in_1c: dict[tuple[str, str], list[str]] = {}
        # Имя коллекции → марки-владельцы по дереву папок 1С. Считается один раз.
        self._owners: dict | None = None
        self._haystack: str | None = None   # весь текст прайса одной строкой
        self._seen_trees: set = set()   # марки, чьё дерево папок уже спрашивали
        self._collection_name = ""      # коллекция текущей сверки — для поиска владельца
        # Последняя ошибка поиска по всей номенклатуре. Молчать о ней нельзя: сорвавшийся
        # поиск ВЫГЛЯДИТ как «ничего не нашлось», и вывод «коллекция новая» становится
        # ложью — 22.09.2026 именно так и вышло, когда 1С отдавала 500 на любой артикул.
        self.search_error = ""
        self.collected: list[PriceTask] = []
        self.marks: list[dict] = []
        self._sheets = None
        self._items_cache: dict[str, list] = {}
        self._tm_names: dict[str, str] = {}     # код марки → её имя В 1С
        self._touched: dict[str, set] = {}      # код марки → коллекции 1С, закрытые сверкой
        self._last_sheet: str = ""              # лист, который агент читал последним
        self._price_cols: dict[str, dict] = {}  # имя листа → названные колонки цен

    def handles(self, name: str) -> bool:
        return name in {t["name"] for t in TOOLS}

    @property
    def sheets(self):
        if self._sheets is None:
            try:
                every = list(parse_price_table(self._content, self._filename) or [])
            except Exception:                           # noqa: BLE001
                logger.warning("Не разобрался прайс %s", self._filename, exc_info=True)
                every = []
            self._sheets = self._narrow(self._pick(every))
        return self._sheets

    def _narrow(self, chosen: list) -> list:
        """Оставить в отмеченных листах строки отмеченных БРЕНДОВ (решение 03.10.2026).

        **СУЖАЕМ ЗДЕСЬ, А НЕ В `_read`**, и это важно по двум причинам. Первая: `_read`
        отдаёт лист через `render_preview`, и если фильтровать там, то нумерация строк и
        листание `from_row` считались бы по НЕотфильтрованному листу — агент дочитывал бы
        «с строки 500» и получал чужие бренды. Отфильтровав раньше, мы не меняем в чтении
        ничего: у нового листа своя нумерация с единицы. Вторая: только здесь видно, что
        после сужения не осталось ни строки, — а это законный исход, о котором обязан узнать
        админ, и узнать ДО того, как мы позовём модель.

        **Лист, где бренд не обозначен, проходит как есть.** У прайса бывает служебная
        вкладка без брендов вовсе, и выбросить её молча значило бы спрятать часть файла по
        признаку, которого в ней нет.

        **Способов обозначить бренд три** (решение админа 04.10.2026): колонка,
        горизонтальный разделитель, картинка-баннер. Выбирает между ними `brand_map`, и здесь
        разницы между ними нет вовсе — строки уже розданы брендам.
        """
        if self._marks is None:
            return chosen

        # ВЫБОР БРЕНДОВ ОТНОСИТСЯ ТОЛЬКО К ЛИСТАМ, ГДЕ БРЕНД ВООБЩЕ ОБОЗНАЧЕН (04.10.2026).
        # Это свойство ЛИСТА, а не формата: у FLOOR SERVICE колонки нет на «КЛЕЙ»,
        # «ИЗМЕНЕНИЯ» и «Скидки розница», а у четырёх форматов из пяти бренд не обозначен ни
        # на одном листе. Без этой проверки пустой список брендов (а он пуст у всех, пока
        # админ не расставил флажки) остановил бы разбор ЦЕЛИКОМ — у форматов, где отмечать
        # нечего в принципе. Нет признака ни в одном отмеченном листе — выбор брендов к ним
        # не относится, работаем как раньше.
        spots = [(sheet, brand_map(sheet, self._logos, self._catalogue))
                 for sheet in chosen]
        if not any(spot is not None for _, spot in spots):
            return chosen

        if not self._marks:
            self.pick_problem = "бренды не отмечены"
            self.skipped_marks = []
            return []

        out = []
        for sheet, spot in spots:
            if spot is None:
                out.append(sheet)
                continue

            whole = brands_in_rows(spot)
            self.whole_rows += sum(rows for _, rows in whole)
            for brand, rows in whole:
                keep = normalize(brand) in {normalize(n) for n in self._marks}
                if keep:
                    self.brand_sizes[brand] = self.brand_sizes.get(brand, 0) + rows
                side = self.parsed_marks if keep else self.skipped_marks
                if brand not in side:
                    side.append(brand)
                if keep:
                    self.kept_rows += rows

            _, chars = rows_cost(sheet, spot, self._marks)
            self.picked_chars += chars
            self.brand_modes[sheet.name] = spot.mode
            out.append(only_brand_rows(sheet, spot, self._marks))

        # ПЕРЕСЕЧЕНИЕ ПУСТО — это не поломка файла и не «расхождений нет». Бренды отмечены,
        # листы отмечены, а общего у них ничего: поставщик переименовал бренд либо отмеченные
        # бренды лежат на другом листе. Выдать это за «работы нет» нельзя.
        if self.whole_rows and not self.kept_rows:
            self.pick_problem = "ни одного отмеченного бренда нет в отмеченных листах"
            return []

        # ОТМЕЧЕНО СЛИШКОМ МНОГО — СПРАШИВАЕМ, А НЕ ПЛАТИМ. Коллекции не выбираются (решение
        # админа), значит бренд берётся целиком, и у Артисаны одна Kerama это 6 702 строки
        # ≈ 200 тыс. токенов ≈ $2 за одну загрузку; дальше история ручного цикла несёт их в
        # каждый следующий запрос. Молчаливый перерасход — ровно то, против чего заводился
        # весь механизм, поэтому модель не зовём вовсе, а называем цифры: решать, платить ли
        # за такой разбор, не наше дело.
        if self.kept_rows > BIG_BRAND_ROWS:
            self.pick_problem = (
                f"отмечено слишком много — {self.kept_rows} строк "
                f"≈ {self.picked_chars // 4} токенов при пределе {BIG_BRAND_ROWS} строк")
            return []

        return out

    def _pick(self, every: list) -> list:
        """Оставить листы, отмеченные админом.

        **НИ ОДНОГО ФЛАГА — НЕ РАЗБИРАЕМ НИЧЕГО** (решение админа 02.10.2026). Прайс
        приходит, его листы уезжают в 1С, админ отмечает нужные и сам нажимает «Обновить
        задачи». Обратное умолчание («не выбрано — значит всё») стоило бы полного разбора
        каждого нового файла: у FLOOR SERVICE это $5.83 за четырнадцать листов, из которых
        нужны два.

        Молчаливым это не делает: разбор, которому нечего разбирать, НЕ ЗАПУСКАЕТСЯ вовсе
        (см. `build`), а админ получает сообщение, что листы не отмечены. Ноль задач в этой
        модели — законный результат, он означает «расхождений нет», и выдать его вместо
        «я ничего не смотрел» нельзя ни при каких условиях.

        Имена сверяются без учёта регистра и крайних пробелов: в 1С их ставит флажком, но
        командой в Telegram их по-прежнему набирают руками.
        """
        names = [s.name for s in every]
        if not every:
            # Файл не разобрался вовсе — это другая беда, и объясняет её `_read`.
            return []

        if self._only is None:
            # Выбором листов никто не управляет — ведём себя как до 02.10.2026.
            self.parsed_sheets = list(names)
            return every

        wanted = {n.strip().lower() for n in self._only}
        if not wanted:
            self.parsed_sheets = []
            self.skipped_sheets = list(names)
            self.pick_problem = "листы не отмечены"
            return []

        # ДАТА В ИМЕНИ ЛИСТА НЕ ОТМЕНЯЕТ ОТМЕТКУ. У Стройиндустрии главный лист зовётся
        # «Прайс от 20.04.2026», а месяцем позже — «Прайс от 01.10.2026»: точное сравнение
        # снимало бы флажок с того же самого листа каждый месяц, молча и по-прежнему
        # уверенно (бой 02.10.2026). Запасной проход сверяет имена правилом сигнатуры
        # (`sheet_key`: числа → «#»), и точное совпадение по-прежнему решает первым.
        loose = {sheet_key(n) for n in self._only}
        chosen = [s for s in every
                  if s.name.strip().lower() in wanted or sheet_key(s.name) in loose]
        found = {s.name.strip().lower() for s in chosen}
        found_loose = {sheet_key(s.name) for s in chosen}
        self.unknown_sheets = [n for n in self._only
                               if n.strip().lower() not in found
                               and sheet_key(n) not in found_loose]

        self.parsed_sheets = [s.name for s in chosen]
        self.skipped_sheets = [s.name for s in every if s not in chosen]

        if not chosen:
            # Поставщик переименовал листы — отмеченных в файле больше нет. Разбирать
            # нечего, и сказать об этом надо громко: иначе «задач нет» прочтётся как
            # «расхождений нет».
            self.pick_problem = "ни один отмеченный лист не найден в файле"
        return chosen

    async def execute(self, name: str, inp: dict):
        """Инструменты синхронные, и ходят в 1С — поэтому исполняются В ПОТОКЕ.

        Прежде они звались прямо из цикла событий, и выгрузка марки по VPN (минуты) замораживала
        ВЕСЬ бот: Telegram не отвечал, очередь 1С не опрашивалась, форма писала «агент не
        отвечает», а прерывание сборки было некому услышать (бой 08.10.2026: одиннадцать минут
        тишины между двумя кругами по Кераматике). Состояние набора инструментов поток не
        делит ни с кем: ручной цикл зовёт их строго по одному.
        """
        handlers = {"read_price": self._read, "get_selling_tm": lambda _: self._tm(),
                    "compare_with_1c": self._compare, "add_task": self._add}
        handler = handlers.get(name)
        if handler is None:
            return f"Неизвестный инструмент: {name}"
        try:
            return await asyncio.to_thread(handler, inp)
        except Exception as exc:                        # noqa: BLE001
            logger.exception("Инструмент %s сорвался", name)
            return f"Ошибка инструмента: {exc}"


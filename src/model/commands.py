"""Команды визуалов и правила их разбора (§7 specs/agent-workflow-model.md).

Визуал кладёт команду в очередь, агент забирает её своим циклом и применяет. Здесь — чистая
часть: какие бывают команды, какие из них схлопываются и кто из пришедших за один цикл
работает первым. Ни базы, ни Telegram.

**Каждая команда несёт время своего создания НА СТОРОНЕ ВИЗУАЛА.** Не время попадания в
очередь и не порядок обхода провайдеров: иначе один визуал был бы всегда «главнее» другого,
а при сетевой задержке «первым» оказался бы тот, кто нажал позже.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from enum import Enum


def now() -> str:
    return datetime.now(timezone.utc).isoformat()


class CommandKind(str, Enum):
    SUBMIT_PRICE = "принять прайс"
    EXECUTE_TASK = "выполнить задачу"
    SET_TASK_STATUS = "сменить статус задачи"
    SET_PRICE_STATUS = "сменить статус прайса"
    EDIT_TASK_DESCRIPTION = "изменить описание задачи"
    DELETE_TASK = "удалить задачу"
    REBUILD_TASKS = "пересобрать задачи"
    DESTROY_PRICE = "уничтожить прайс"
    RELEASE_LOCK = "снять захват"
    # Переименование поставщика — ЕДИНСТВЕННАЯ команда не про прайс и не про задачу.
    # Приходит из 1С, когда админ правит карточку в зеркале справочника: имя там видно
    # в таблице прайсов, и расхождение с моделью читалось бы как два разных поставщика.
    # Обратный ход (модель → 1С) идёт снимком и команды не требует.
    RENAME_SUPPLIER = "переименовать поставщика"
    # Листы, которые разбирать у формата прайса. Тоже не про прайс и не про задачу: адресат
    # — СИГНАТУРА, и действует выбор на все будущие файлы этого формата. Приходит из формы
    # 1С (двойной щелчок по имени файла в таблице прайсов) и из Telegram.
    SET_SIGNATURE_SHEETS = "изменить листы формата"
    # Бренды внутри листа — второй список у того же формата (решение админа 03.10.2026).
    # Адресат тот же, СИГНАТУРА, но решение другое: к разбору уходит ПЕРЕСЕЧЕНИЕ отмеченных
    # листов и отмеченных брендов. Несёт заодно привязку бренда к марке 1С, скидку от
    # розницы по каждому бренду и курс евро для прайса — всё это админ задаёт одной формой.
    SET_SIGNATURE_MARKS = "изменить бренды формата"
    # ОДНА КОМАНДА НА ОБА СПИСКА (решение админа 03.10.2026: листы и бренды — одна форма с
    # общими «Обновить» и «Сохранить»). Двумя командами это сделать НЕЛЬЗЯ: адрес у них
    # одинаковый — прайс и задача 0, — и защита от второго нажатия
    # (`НезакрытаяКоманда(Прайс, Задача)`) отклонила бы вторую с «по этому прайсу уже
    # отправлена команда». Одна команда — одна защита, одна надпись ожидания, один исход.
    #
    # Прежние два вида оставлены: команда могла лежать в очереди в момент выкладки, а
    # очередь переживает перезапуск (`requeue_stale`).
    SET_SIGNATURE_FORMAT = "изменить формат прайса"
    # ПРЕРВАТЬ РАБОТУ ПО ПРАЙСУ — сборку задач или выполняемую задачу (решение админа
    # 08.10.2026: на плохом VPN сборка «подвисала», и остановить её было нечем, кроме
    # перезапуска бота). Единственная команда, которую цикл забирает И ВО ВРЕМЯ работы:
    # всё остальное ждёт конца прогона, а эта ровно для того, чтобы его не ждать
    # (`AgentLoop._apply_watched`). Схлопывается по прайсу как обычно — и это полезно:
    # ещё не взятую сборку того же прайса она замещает, то есть та просто не начнётся.
    INTERRUPT = "прервать работу"


#: Потолок доверия к метке — СТРАХОВКА, а не основной механизм. Основную работу делает
#: измеренное смещение часов источника; потолок ловит случай, когда измерить не вышло или
#: измерение само оказалось мусором. Час, а не пять минут: команда могла честно пролежать в
#: очереди 1С, пока агент был выключен, и такую метку портить нельзя — она верна.
MAX_SKEW_SECONDS = 3600


def sort_time(reported: str | None, offset_seconds: float = 0.0,
              agent_now: datetime | None = None, trust: bool = True) -> tuple[str, str]:
    """Время, по которому команда участвует в «кто первый». Возвращает (время, причина).

    **Зачем вообще поправка.** Порядок решает время создания НА СТОРОНЕ ВИЗУАЛА (§7), но
    часы визуала могут быть сбиты — тогда он либо всегда выигрывает, либо всегда проигрывает,
    и вся затея с честным порядком рушится.

    Расхождение возможно ровно у ОДНОГО визуала — 1С: она отдельный сервер. Команды
    Telegram создаёт сам процесс бота, и их метка — это и есть часы агента, смещение нулевое
    по построению.

    Поэтому `offset_seconds` — измеренное смещение часов источника относительно наших
    (`время_визуала − наше_время` в момент опроса). Вычитая его, приводим метку к нашим
    часам.

    **Потолок доверия — страховка.** Основную работу делает поправка; потолок ловит случай,
    когда смещение измерить не вышло (`trust=False`) или оно само оказалось мусором. Порог
    намеренно велик: команда могла честно пролежать в очереди 1С, пока агент был выключен,
    и такая метка ВЕРНА — портить её нельзя.

    Причина возвращается наружу, чтобы подмена времени была видна в логе, а не молча меняла
    порядок.
    """
    agent_now = agent_now or datetime.now(timezone.utc)
    if not trust:
        return agent_now.isoformat(), "часы источника неизвестны"
    if not reported:
        return agent_now.isoformat(), "метки нет"

    try:
        stamp = datetime.fromisoformat(reported)
    except ValueError:
        return agent_now.isoformat(), "метка не разобрана"

    if stamp.tzinfo is None:
        stamp = stamp.replace(tzinfo=timezone.utc)

    corrected = stamp - timedelta(seconds=offset_seconds)
    drift = abs((corrected - agent_now).total_seconds())
    if drift > MAX_SKEW_SECONDS:
        return agent_now.isoformat(), f"часы источника разошлись на {int(drift)} с"
    return corrected.isoformat(), ""


@dataclass
class Command:
    """Одна команда визуала.

    `price_id` заполняется и для задачных команд: по нему работает «кто первый» и захват
    прайса, а искать прайс по задаче в момент разбора очереди — лишний круг к базе.
    """
    kind: CommandKind
    source: str = ""                    # «telegram», «1c» — какой провайдер принёс
    actor: str = ""                     # кто из админов; захват принадлежит ему
    price_id: int | None = None
    task_id: int | None = None
    payload: dict = field(default_factory=dict)
    created_at: str = field(default_factory=now)     # как сообщил визуал — для диагностики
    sort_at: str = ""                                # приведённое к нашим часам (`sort_time`)
    id: int | None = None
    #: НОМЕР В ПАЧКЕ — в каком порядке инициатор хочет их выполнить (0 — не сказано).
    #:
    #: Нужен потому, что время создания тут НЕ РАЗЛИЧАЕТ команды: нажатие одно, а
    #: `ТекущаяДата()` в 1С имеет секундную точность, и все команды пачки получают ОДНУ
    #: метку. Ничья разрешалась номером в очереди агента, то есть порядком, в котором их
    #: вернула 1С, а она сортирует по `Идентификатор` — СЛУЧАЙНОМУ GUID. Админ выделил
    #: пять задач и увидел «со второй по последнюю, первая в конце» (бой 03.10.2026).
    #:
    #: ЖИВЁТ В НАГРУЗКЕ, а не отдельной колонкой очереди: нагрузка и так едет в базу
    #: строкой JSON, переживает перезапуск и схлопывание, — а колонка потребовала бы
    #: миграции таблицы ради числа, которое нужно ровно на один оборот. Остальному коду
    #: лишний ключ безразличен: он читает `description`, `status`, `signature` по именам.
    seq: int = 0

    def __post_init__(self) -> None:
        # Без поправки порядок считается по сырой метке: для Telegram это одно и то же,
        # потому что её ставит тот же процесс.
        if not self.sort_at:
            self.sort_at = self.created_at

        # Номер в пачке восстанавливаем из нагрузки — в том числе ПОСЛЕ очереди: оттуда
        # команда приходит собранной из колонок, и поле, которого в таблице нет,
        # обнулилось бы молча, а вместе с ним и порядок.
        if not self.seq:
            try:
                self.seq = int((self.payload or {}).get("seq") or 0)
            except (TypeError, ValueError, AttributeError):
                self.seq = 0

    def coalesce_key(self) -> tuple | None:
        """Ключ замещения — **только объект**: задача либо прайс. Вид в него НЕ входит.

        Более новая команда по тому же объекту всегда замещает лежащую в очереди, какого бы
        вида та ни была. В модель приезжает последнее решение админа, а не цепочка
        промежуточных.

        **Почему не «вид + объект».** Разбирая пример админа: он правит описание задачи и
        тут же жмёт «Выполнить», успевая между опросами. При ключе с видом это две разные
        команды, обе попадают в одну пачку — и там их встречает правило «кто первый»
        (§7): правка выполняется, а «Выполнить» отклоняется с «прайс занят». Штатный
        рабочий порядок ломался бы на ровном месте.

        При ключе по объекту они сливаются в одну команду «выполнить задачу 5», которая
        **несёт свежий текст описания** (payload замещающей объединяется с замещаемой — см.
        `CommandQueue.put`). Агент получает последнюю версию задания, как и требуется.

        None — замещать не по чему: у команды нет объекта (приём нового файла), и две
        такие команды это два разных файла.
        """
        # ПЕРЕИМЕНОВАНИЕ НЕ СХЛОПЫВАЕТСЯ, и это не недосмотр. Замещение в очереди ищет
        # соседа ПО КОЛОНКАМ `price_id`/`task_id` (`CommandQueue.put`), а у этой команды
        # нет ни того, ни другого: она схлопнулась бы с переименованием ДРУГОГО
        # поставщика, и одно из двух имён потерялось бы. Терять тут нечего и так:
        # переименования идемпотентны и применяются по порядку, последнее побеждает.
        if self.kind == CommandKind.RENAME_SUPPLIER:
            return None

        # ВЫБОР ЛИСТОВ НЕ СХЛОПЫВАЕТСЯ, хотя номер прайса у него есть. Номер нужен ему
        # ТОЛЬКО для адресации визуала: по нему форма гасит кнопки и показывает надпись
        # «Записываю список листов…» (решение админа 02.10.2026). Объект же у команды
        # другой — СИГНАТУРА формата, и схлопнувшись с «сменить статус прайса 6», она
        # потеряла бы одно из двух несвязанных решений админа.
        if self.kind == CommandKind.SET_SIGNATURE_SHEETS:
            return None

        # ВЫБОР БРЕНДОВ — по той же причине и с той же оговоркой: номер прайса у команды
        # есть, но он нужен лишь визуалу (надпись ожидания и курс евро этого прайса), а
        # объект решения — сигнатура формата.
        if self.kind == CommandKind.SET_SIGNATURE_MARKS:
            return None

        if self.kind == CommandKind.SET_SIGNATURE_FORMAT:
            return None

        target = self.task_id if self.task_id is not None else self.price_id
        if target is None:
            return None
        return ("task" if self.task_id is not None else "price", target)

    def label(self) -> str:
        target = (f"задача {self.task_id}" if self.task_id is not None
                  else f"прайс {self.price_id}" if self.price_id is not None else "")
        return f"{self.kind.value} ({target})".strip()


@dataclass(frozen=True)
class Rejected:
    """Команда, которую не взяли в работу, и почему — визуалу надо что-то ответить."""
    command: Command
    reason: str


def order_batch(commands: list[Command]) -> list[Command]:
    """Упорядочить пачку по времени создания на стороне визуала.

    Сортируем по `sort_at` — метке, приведённой к нашим часам (`sort_time`), а не по сырой:
    сбитые часы визуала иначе давали бы ему вечное преимущество.

    **Ничью решает `seq` — номер в пачке**, и только потом номер в очереди (`id`). Одно
    нажатие по нескольким задачам даёт команды с ОДНОЙ меткой времени: у `ТекущаяДата()`
    секундная точность. Пока ничью разрешал `id`, порядок наследовался от того, как строки
    вернула 1С, а она упорядочивает по `Идентификатор` — случайному GUID; админ видел
    «выполняется со второй задачи по последнюю, первая в конце».

    `seq` = 0 у всех, кто порядка не назвал (одиночные нажатия, Telegram): такие команды
    по-прежнему разбираются по `id`, и для них ничего не изменилось.
    """
    return sorted(commands,
                  key=lambda c: (c.sort_at or c.created_at, c.seq or 0, c.id or 0))


def group_by_actor(commands: list[Command]) -> list[tuple[str, list[Command]]]:
    """Разложить пачку по инициаторам, упорядочив ГРУППЫ по самому раннему нажатию.

    Занятость считается отдельно для каждого инициатора (`locks.busy_for`): свой захват
    админа не блокирует, чужой блокирует. Поэтому пачка и разбирается группами — но
    порядок групп решает, кто из двух админов выиграет спор за прайс: первая группа берёт
    захват, вторая получает «прайс занят другим администратором».

    **Порядок — по времени НАЖАТИЯ, а не по тому, как строки легли в очередь.** Иначе
    побеждал бы тот, чьего провайдера опросили раньше, — то самое, что правило «кто
    первый» (§7) и запрещает. Внутри группы порядок задаёт `order_batch`.
    """
    groups: dict[str, list[Command]] = {}
    for command in commands:
        groups.setdefault(command.actor, []).append(command)

    def earliest(pair: tuple[str, list[Command]]) -> tuple[str, int]:
        first = order_batch(pair[1])[0]
        return (first.sort_at or first.created_at, first.id or 0)

    return sorted(groups.items(), key=earliest)


def plan_batch(commands: list[Command],
               busy_prices: set[int] | None = None) -> tuple[list[Command], list[Rejected]]:
    """Разобрать пачку: что выполняем, что отклоняем.

    **Правило «кто первый» действует на ВСЕ команды** (§7): если за цикл пришло несколько
    команд по одному прайсу, выполняется самая ранняя, остальным отвечаем «прайс занят».
    Тот же жёсткий запрет, что и захват прайса (§5.1), просто на входе.

    Две команды одного вида по ОДНОМУ объекту до этого правила не доходят — они замещают
    друг друга ещё в очереди (`coalesce_key`), и в пачке остаётся одна.

    `busy_prices` — прайсы, закрытые для инициатора к началу цикла. Считать их должен
    вызывающий: захват свой же админ не блокирует, поэтому набор зависит от того, ЧЕЙ это
    цикл (`locks.busy_for`).

    Команда без прайса (приём нового файла) под правило не попадает: она ещё не относится
    ни к какому прайсу.

    **РАЗНЫЕ ЗАДАЧИ ОДНОГО ПРАЙСА ДРУГ ДРУГА НЕ ОТКЛОНЯЮТ** (решение админа 03.10.2026:
    выделить в форме несколько задач и нажать «Выполнить» один раз). Прежде правило брало
    прайс ЦЕЛИКОМ, и из пяти отмеченных задач выполнялась одна, а четыре получали «прайс
    занят» — отказ по действию, которое админ сделал осознанно и одним нажатием.

    Ограничение при этом не снято, а СУЖЕНО до настоящего конфликта:

    * команда ПО ПРАЙСУ (статус, пересборка, уничтожение, выбор листов) требует прайс
      целиком — она меняет то, на что смотрят все его задачи, и соседство с их
      выполнением означало бы разный результат в зависимости от того, что успело первым;
    * команды ПО ЗАДАЧАМ соседствуют, пока задачи разные: объекты не пересекаются;
    * две команды по ОДНОЙ задаче сюда не доходят — они схлопываются в очереди
      (`coalesce_key`), и в пачке остаётся последнее решение админа.

    Кто из двух видов побеждает, решает «кто первый» (`order_batch`): пришла раньше
    команда по прайсу — задачи ждут следующего оборота, и наоборот.

    **ВЫПОЛНЯТЬСЯ ОНИ БУДУТ ПО ОЧЕРЕДИ, А НЕ РАЗОМ.** Разрешение попасть в один оборот —
    не разрешение писать в 1С одновременно: захват прайса один, у него поколение, и
    параллельные прогоны затирали бы друг другу записи. Служба применяет команды пачки
    последовательно, и это ровно то, что видно в форме: колесико загорается у всех
    отмеченных задач сразу и гаснет по одной.
    """
    busy = set(busy_prices or ())
    whole: set[int] = set()         # прайсы, взятые командой ПО ПРАЙСУ
    touched: set[int] = set()       # прайсы, по которым в пачке уже есть любая команда
    tasks: set[int] = set()         # задачи, уже занятые в этой пачке
    run: list[Command] = []
    rejected: list[Rejected] = []

    for command in order_batch(commands):
        price_id = command.price_id
        if price_id is None:
            run.append(command)
            continue

        if price_id in busy:
            rejected.append(Rejected(command, "прайс занят другим администратором"))
            continue

        if price_id in whole:
            rejected.append(Rejected(command, "прайс занят: по нему уже идёт другая команда"))
            continue

        task_id = command.task_id
        if task_id is None:
            # Команда про прайс целиком: соседство с задачными ей запрещено в обе стороны.
            if price_id in touched:
                rejected.append(
                    Rejected(command, "прайс занят: по его задачам уже идут команды"))
                continue
            whole.add(price_id)
        elif task_id in tasks:
            # Схлопывание в очереди такого не оставляет; остаётся на случай, когда команды
            # пришли из разных визуалов и схлопнуться не успели.
            rejected.append(Rejected(command, "по этой задаче уже идёт другая команда"))
            continue
        else:
            tasks.add(task_id)

        touched.add(price_id)
        run.append(command)

    return run, rejected

"""Инвентаризация свойства «Коллекция» по всему каталогу (команда `/empty_collections`).

ЗАЧЕМ ОТДЕЛЬНАЯ КОМАНДА, если сверка это и так считает. `compare_with_1c` возвращает
`без_свойства_Коллекция`, но только по коллекциям, КОТОРЫХ КОСНУЛСЯ ПРАЙС: сверка идёт от
разбираемого файла и о марке, по которой прайса не приходило, не знает ничего. Это отлов
попутный — «раз уж мы сюда пришли», — а вопрос «где вообще в каталоге дыры» им не
закрывается.

**СЧИТАЕТ КОД, МОДЕЛЬ НЕ УЧАСТВУЕТ ВОВСЕ.** Решать тут нечего: свойство либо заполнено,
либо нет. Круг ручного цикла несёт всю историю и стоит ~$0.097, а обход тридцати марок
через модель стоил бы десятки долларов — при том, что ответ целиком выводится из выгрузки,
которая и так приходит. Здесь это не экономия ради экономии: инвентаризация по всему
каталогу через модель была бы попросту недоступна по цене.

**ПОЧЕМУ ПУСТОЕ СВОЙСТВО — ЭТО ДЫРА, А НЕ МЕЛОЧЬ.** По нему коллекция опознаётся на сайте.
Пустое заставляет выводить имя из ПАПКИ, а в имени папки по §19.5 стоит размер — и он
уезжает в середину наименования: «Ламинат A+ Floor Ле Паркет 600x600x14 Авила».
`collection_of` от этого защищает (снимает размерный хвост), но защита эта — костыль на
каждом чтении, а не исправленные данные.

**СНЯТЫЕ НЕ СЧИТАЮТСЯ.** Их не правят: они уже сняты, и работа по ним — перенос в папки
снятых, а не заполнение свойств (решение админа 21.09.2026). Показав их, мы бы предложили
работу, которой нет.
"""
from __future__ import annotations

from dataclasses import dataclass

from src.model.normalize import collection_of

#: Сколько кодов 1С показываем в строке. Не список позиций, а образец: по нему видно, куда
#: смотреть, а полный перечень на сорок кодов в чате никто не читает — он и так получается
#: из задачи «изменение свойств».
SAMPLE = 3

#: Ни свойства, ни имени папки. Такую строку нельзя заполнить по имени коллекции — заполнять
#: нечем, и это другая работа, поэтому она стоит отдельно, а не в общей куче.
UNKNOWN = "папка не определилась"


@dataclass(frozen=True)
class Gap:
    """Одна дыра: сколько позиций одной коллекции стоят без свойства."""
    tm: str
    collection: str
    product_type: str
    count: int
    sample: tuple[str, ...]        # коды 1С, первые SAMPLE

    @property
    def where(self) -> str:
        """Адрес — как у задач по прайсу: «марка / коллекция»."""
        return f"{self.tm} / {self.collection}"


def scan(tm: str, items) -> list[Gap]:
    """Дыры по одной марке, от крупных к мелким.

    Группируем по ВЫВЕДЕННОЙ коллекции (`collection_of`), а не по свойству: свойства-то и
    нет — оно пустое, за тем и пришли. Вид товара в ключе, потому что одноимённые коллекции
    у разных видов — разные коллекции, и заполнять их будут по отдельности.
    """
    buckets: dict[tuple[str, str], list] = {}
    for item in items:
        if getattr(item, "not_exported", False):
            continue
        if (getattr(item, "collection", "") or "").strip():
            continue
        name = collection_of(item).strip() or UNKNOWN
        buckets.setdefault((name, (item.product_type or "").strip()), []).append(item)

    gaps = [Gap(tm=tm, collection=name, product_type=kind, count=len(rows),
                sample=tuple(i.ref for i in rows[:SAMPLE]))
            for (name, kind), rows in buckets.items()]
    # По убыванию числа: крупная дыра — это коллекция, не заведённая как следует, и она
    # важнее одиночной позиции, которую забыли при добавлении.
    return sorted(gaps, key=lambda g: (-g.count, g.collection))


def _number(value: int) -> str:
    """Разряды через пробел: «3 418» читается с одного взгляда, «3418» — нет. Так же, как
    в отчёте о расходе токенов (`src/agent/usage.py`)."""
    return f"{int(value):,}".replace(",", " ")


def render(gaps: list[Gap], *, marks: int, live: int,
           failed: list[str] | None = None, lost: int = 0,
           scope: str = "") -> str:
    """Отчёт админу.

    ПУСТОЙ ОТЧЁТ ТОЖЕ ПЕЧАТАЕТСЯ, в отличие от сводки менеджерам: там молчание значит
    «новостей нет», а здесь админ сам спросил и обязан получить ответ — «ни одной дыры» это
    и есть ответ, а тишина читалась бы как «команда не сработала».
    """
    failed = list(failed or [])
    head = ("Свойство «Коллекция» не проставлено: "
            f"{_number(sum(g.count for g in gaps))} поз.")
    if not gaps:
        head = "Свойство «Коллекция» проставлено везде."

    where = f" по марке «{scope}»" if scope else ""
    lines = [head, "",
             f"Просмотрено{where}: марок {marks}, живых позиций {_number(live)}.", ""]

    for gap in sorted(gaps, key=lambda g: (-g.count, g.tm, g.collection)):
        tail = f" — {', '.join(gap.sample)}" if gap.sample else ""
        kind = f" [{gap.product_type}]" if gap.product_type else ""
        lines.append(f"— {gap.where}{kind}: {gap.count}{tail}")

    # НЕПОЛНОТУ НАЗЫВАЕМ ВСЛУХ. Отчёт, посчитанный по неполной выгрузке, выглядит точно так
    # же, как полный, и «дыр нет» тогда значит «мы не смотрели» — это ровно тот молчаливый
    # обман, из-за которого правило «называть потери» и появилось.
    if lost:
        lines += ["", f"⚠️ 1С не отдала {lost} поз. — они в счёт не вошли."]
    if failed:
        lines += ["", "⚠️ Не удалось выгрузить марки: " + ", ".join(failed)]

    if gaps:
        lines += ["", "Заполняется задачей «изменение свойств» по коллекции: агент "
                      "проставит значение по её имени."]
    return "\n".join(lines)


def split(text: str, limit: int = 3900) -> list[str]:
    """Разбить на сообщения Telegram ПО СТРОКАМ, а не по символам.

    Жёсткая резка на 4096 рвёт строку посреди адреса, и обрывок читается как отдельная
    коллекция. Предел взят с запасом от лимита в 4096: в сообщение добавляется заголовок
    «часть N».
    """
    out: list[str] = []
    current = ""
    for line in text.split("\n"):
        candidate = f"{current}\n{line}" if current else line
        if len(candidate) > limit and current:
            out.append(current)
            current = line
        else:
            current = candidate
        # Одна строка длиннее предела — режем её саму, деваться некуда.
        while len(current) > limit:
            out.append(current[:limit])
            current = current[limit:]
    if current:
        out.append(current)
    return out or [""]

"""Сводка по прайсу для МЕНЕДЖЕРОВ (решение админа 28.09.2026).

Уходит один раз — когда админ закрывает прайс, подтвердив это в диалоге. Не после каждой
задачи: менеджеру нужна картина «что изменилось в товарах», а не лента операций.

**СОБИРАЕТСЯ ИЗ ДАЙДЖЕСТОВ, А НЕ ИЗ ТЕКСТА РЕЗУЛЬТАТА.** Результат задачи — рассказ
агента, и по нему не отличить «обновлены цены у четырёх» от «менять было нечего»: обе
задачи закрыты как выполненные. Дайджест же снимается в момент записи и считает ровно то,
что 1С приняла.

**ЧЕГО В СВОДКЕ НЕТ, И ЭТО РЕШЕНИЯ, А НЕ УПУЩЕНИЯ.**

* Нормализации нет вовсе: регистр и пробелы в наименовании — не та новость, ради которой
  дёргают менеджеров.
* Конкретных товаров нет: адресация ровно такая же, как у задач по прайсу, — «марка /
  коллекция» и число позиций. Список из сорока артикулов в чате не читают.
* Пустой сводки нет: не менялось ничего — не отправляется ничего. Сообщение «изменений
  нет» бесполезно получателю и обесценивает следующие.
"""
from __future__ import annotations

#: Что менеджерам не показываем. Ключ дайджеста, а не вид задачи: нормализация случается
#: и внутри других работ (`plan.normalized` в записи справочника).
HIDDEN = {"нормализованы имена"}

#: Порядок строк внутри одной коллекции. Сперва то, что меняет состав каталога, потом
#: цены, потом уточнения: менеджер читает сверху и чаще всего дальше первой строки не
#: идёт.
ORDER = ("заведены новые", "сняты с производства", "обновлены цены",
         "уточнены размеры", "уточнена упаковка", "перенесены в другую папку",
         "изменены свойства")


def _rank(kind: str) -> int:
    return ORDER.index(kind) if kind in ORDER else len(ORDER)


def visible(digest: dict) -> dict:
    """Дайджест без скрытого и без нулей."""
    return {k: int(v) for k, v in (digest or {}).items()
            if k not in HIDDEN and int(v or 0) > 0}


def summary(price, header: str = "") -> str | None:
    """Текст для менеджеров либо None, если рассказывать не о чем.

    `header` — ИМЯ ПОСТАВЩИКА (решение админа 28.09.2026). Имя файла —
    «ПРАЙС_ЛАМИНАТ_СТРОЙИНДУСТРИЯ_с_20_04_2026.xlsx» — менеджеру ничего не говорит и
    выглядит как внутренняя кухня; поставщик это то, чем он поставку и называет. Пусто —
    откатываемся на файл: безымянная сводка хуже некрасивой.
    """
    by_address: dict[str, dict] = {}
    for task in price.tasks:
        counts = visible(getattr(task, "digest", None))
        if not counts:
            continue
        # Адрес — тот же, что у задачи в форме: «марка / коллекция». Второй способ
        # называть одно и то же место разошёлся бы с первым.
        where = task.address.label()
        row = by_address.setdefault(where, {})
        for kind, number in counts.items():
            row[kind] = row.get(kind, 0) + number

    if not by_address:
        return None

    name = header or getattr(price.supplier_price, "filename", "") or "прайс"
    lines = [f"Обновлён каталог по прайсу «{name}»:", ""]
    for where in sorted(by_address):
        parts = sorted(by_address[where].items(), key=lambda kv: _rank(kv[0]))
        lines.append(f"— {where}: "
                     + ", ".join(f"{kind} ({number})" for kind, number in parts))

    # Подписи «подробности — у администратора» здесь нет намеренно (решение админа
    # 28.09.2026): она не несёт ничего, к кому идти за подробностями менеджер знает и так,
    # а лишняя строка в коротком сообщении съедает его краткость.
    return "\n".join(lines)

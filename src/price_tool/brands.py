"""Бренды внутри ОДНОГО листа прайса: где колонка, какие бренды, как оставить нужные.

**ЗАЧЕМ.** Выбор листов (`supplier_signature.sheets`) не помогает прайсу, у которого лист
один. «Остатки 01.10.2026» — одна вкладка, 1286 строк, 23 бренда: полный разбор это 88 тыс.
токенов только на загрузку таблицы, а из 23 брендов 13 в справочнике 1С отсутствуют вовсе,
то есть больше половины файла — не работа, а мусор. Значит фильтровать надо СТРОКИ, а
признак для фильтра у этого формата стоит прямо в колонке «Бренд».

**КОЛОНКУ НАХОДИТ КОД, А НЕ МОДЕЛЬ.** Список брендов нужен ДО первого обращения к модели:
по нему админ ставит флажки, и только потом идёт разбор. Спросить модель здесь не у кого —
платить за круг цикла, чтобы прочитать заголовок, тоже незачем.

**СРАВНЕНИЕ ЗАГОЛОВКА — ТОЧНОЕ, НЕ ВХОЖДЕНИЕМ.** Рядом с «Бренд» в том же файле стоят
«Фабрика» и «Код производителя». Первая — ЗАВОД, а не бренд: на смешении завода с маркой мы
уже обожглись у Peli (`normalize.shared_tail`), и попади она сюда — фильтр резал бы прайс по
изготовителю. Вторая вхождением совпала бы с «производитель» и увела бы колонку на артикул.

Модуль чистый: ни базы, ни сети, ни 1С.
"""
from __future__ import annotations

from dataclasses import dataclass

from src.price_tool.parser import Sheet, non_empty_rows
from src.price_tool.scope import normalize

#: Заголовки, за которыми стоит марка товара. Только ТОЧНОЕ совпадение после `normalize`.
BRAND_HEADERS = frozenset({
    "бренд", "брэнд", "тм", "марка", "торговая марка", "товарная марка",
    "производитель", "brand",
})

#: Как глубоко искать шапку. Та же мерка, что у сигнатуры формата (`signature.SCAN_ROWS`):
#: заголовок ниже двадцатой строки — это не заголовок, а строка данных.
SCAN_ROWS = 20


@dataclass(frozen=True)
class BrandColumn:
    """Где стоит бренд и где кончается шапка.

    `header_rows` — сколько ПЕРВЫХ непустых строк листа занимает шапка. Нужны они целиком:
    у этого формата заголовки размазаны по четырём строкам («Фабрика | Бренд | Коллекция…»,
    ниже «шт. в кор. | м2 в кор.», ниже «Цена | Свободный остаток»), и, отдав модели только
    строки товаров, мы отдали бы таблицу без названий колонок.
    """
    column: int
    header_rows: int


def find_brand_column(sheet: Sheet) -> BrandColumn | None:
    """Колонка бренда и высота шапки. None — в этом листе бренд колонкой не выделен.

    Шапка кончается на ПЕРВОЙ строке, где в найденной колонке есть значение: ниже идут
    товары. Считать по-другому (например, «шапка это строка с заголовком») нельзя — между
    заголовком и данными у этого формата лежат ещё три строки уточнений.
    """
    rows = non_empty_rows(sheet)

    column = None
    header_at = 0
    for number, row in enumerate(rows[:SCAN_ROWS], 1):
        for index, cell in enumerate(row):
            if normalize(str(cell or "")) in BRAND_HEADERS:
                column, header_at = index, number
                break
        if column is not None:
            break

    if column is None:
        return None

    for number, row in enumerate(rows, 1):
        if number <= header_at:
            continue
        if len(row) > column and str(row[column] or "").strip():
            return BrandColumn(column=column, header_rows=number - 1)

    # Заголовок есть, а данных под ним нет — фильтровать нечего и незачем.
    return None


def _effective(rows: list[list[str]], spot: BrandColumn) -> list[tuple[int, str]]:
    """Строки данных с их брендом: `(номер строки, бренд)`, нумерация с единицы.

    **ПУСТАЯ ЯЧЕЙКА — ЭТО ОБЪЕДИНЁННАЯ С ВЕРХНЕЙ**, и значение переносится сверху вниз.
    Иначе объединённые ячейки (а ими размечают бренд чаще всего) порезали бы марку на
    куски: первая строка досталась бы бренду, остальные — никому.

    Строка выше первых данных сюда не попадает: шапка не принадлежит ни одному бренду.
    """
    out: list[tuple[int, str]] = []
    current = ""
    for number, row in enumerate(rows, 1):
        if number <= spot.header_rows:
            continue
        value = str(row[spot.column] or "").strip() if len(row) > spot.column else ""
        # ПОВТОРЁННАЯ ШАПКА — НЕ БРЕНД И НЕ ТОВАР. У FLOOR SERVICE заголовок повторяется
        # ниже по листу («АКЦИИ», «ПОДЛОЖКА И ПЛИНТУС»), и слово «Производитель» приезжало
        # в список брендов наравне с Kronotex. Отличить его можно ровно так: это и есть
        # одно из тех слов, по которым колонка была найдена.
        #
        # Такая строка не принадлежит НИ ОДНОМУ бренду, поэтому перенос сверху вниз здесь
        # ОБРЫВАЕТСЯ: приписав разделитель верхнему бренду, мы и счёт его строк завысили
        # бы, и отдали бы модели заголовок как его товар. Разрыв безопасен и для следующей
        # строки: ниже разделителя начинается новый раздел, и бренд в нём назван заново.
        if normalize(value) in BRAND_HEADERS:
            current = ""
            continue
        if value:
            current = value
        if current:
            out.append((number, current))
    return out


def brands_in(sheet: Sheet, spot: BrandColumn) -> list[tuple[str, int]]:
    """Бренды листа со числом строк, В ПОРЯДКЕ ФАЙЛА.

    Порядок не алфавитный намеренно: админ ищет бренд глазами там, где он стоит в книге, —
    по той же причине, по которой листы в форме идут порядком вкладок.

    Имя хранится КАК НАПИСАНО: сравнивать будем нормализованное, а показывать — авторское.
    «Italon Керамический гранит» и «Italon Настенная плитка» это два разных ярлыка одного
    поставщика, и сливать их здесь нельзя — какой из них чья марка, решает админ.
    """
    rows = non_empty_rows(sheet)
    seen: dict[str, int] = {}
    order: list[str] = []
    for _, brand in _effective(rows, spot):
        key = normalize(brand)
        if key not in seen:
            seen[key] = 0
            order.append(brand)
        seen[key] += 1
    return [(brand, seen[normalize(brand)]) for brand in order]


def only_brands(sheet: Sheet, spot: BrandColumn, wanted) -> Sheet:
    """Лист из ШАПКИ и строк выбранных брендов.

    Отдаём именно `Sheet`, а не текст: дальше его показывает `render_preview`, и вся
    механика чтения — нумерация строк, листание `from_row`, пометка «ещё N строк не
    показано» — остаётся прежней. Текстом (как делает `find_rows`) это пришлось бы
    переписывать заново и разойтись с ней в мелочах.

    Нумерация у отфильтрованного листа СВОЯ, от единицы: `from_row` считается по тому, что
    агент видит. Исходные номера строк ему ни к чему — он не возвращается к файлу иначе,
    чем через этот же инструмент.

    Пустой `wanted` даёт лист из одной шапки: это законный исход («ни один бренд не
    отмечен»), и обрабатывает его вызывающий, а не мы молча.
    """
    keys = {normalize(name) for name in (wanted or ()) if normalize(name)}
    rows = non_empty_rows(sheet)

    kept = list(rows[:spot.header_rows])
    for number, brand in _effective(rows, spot):
        if normalize(brand) in keys:
            kept.append(rows[number - 1])

    return Sheet(name=sheet.name, rows=kept)

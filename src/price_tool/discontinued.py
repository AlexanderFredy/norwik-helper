"""Куда переносить снятый с производства товар (§19.2.5 спеки).

В 1С папок снятых четырнадцать, и содержимое их перемешано: глобальная «!Номенклатура
снятая с производства» держит 14 видов товара сразу, а в «*(Ламинат)» лежит керамическая
плитка. Разбирать эту кашу задним числом мы не будем — но и множить её нельзя, поэтому у
агента одна целевая папка на вид товара, заданная здесь жёстко.

**Почему таблица в коде, а не запрос в 1С и не промпт.** Это НАШЕ решение, а не факт базы:
в 1С нет данных, из которых следовало бы «для ламината правильная папка вот эта». Отдавать
её из 1С значит хардкодить нашу политику в BSL, где её не покрыть тестом и не поменять без
выкладки сервиса. Отдавать её модели значит превращать поиск по ключу в суждение, а
ошибиться она сможет молча — узнаем, когда товары окажутся в чужой папке.

**Что за 1С остаётся — существование.** Неверный код здесь означает тихую запись в
случайную папку, поэтому перед первым переносом в прогоне таблица сверяется с деревом
`folders` (см. `problems()`), и при расхождении перенос не делается вовсе.

Ключ — КОД вида товара, не имя: имена приходят с хвостовым пробелом («Виниловый ламинат »)
и их переименовывают.

**Отсутствие вида товара в таблице — это отказ, а не повод взять глобальную папку.**
Молчаливый фолбэк в «!Номенклатура снятая с производства» — ровно то, из чего нынешняя
каша и выросла.

Поиск снятого товара (чтобы восстановить, а не заводить дубль) этой таблицей НЕ
пользуется: там смотрим везде — `by-tm` с `include_not_exported=1` и без фильтра по виду
товара (§19.3).
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Target:
    """Целевая папка снятых для одного вида товара."""

    product_type: str   # имя вида товара в 1С — только для сообщений админу
    folder_ref: str     # код папки; им и адресуемся при переносе
    folder_name: str    # имя папки на момент составления таблицы — для сверки, см. problems()
    # Пустое folder_name означает «имени мы не знаем»: папка заведена под нас и товаров в
    # ней ещё нет, поэтому в выгрузке она не встречалась. Сверку имени для такой папки
    # пропускаем — иначе получили бы ложное «переименована» на ровном месте.



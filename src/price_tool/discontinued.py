# Виды товара с действующим ассортиментом, у которых выделенной папки в 1С ещё нет. Пока
# папка не заведена, перенос по виду невозможен — список нужен, чтобы отказ назвал причину,
# а не отделался «вида товара нет в таблице». Сейчас пуст: обои и керамогранит закрыты.
NEEDS_FOLDER: dict[str, str] = {}


def folder_for(product_type_ref: str | None) -> str | None:
    """Код целевой папки снятых. None — переносить нельзя, нужен вопрос админу."""
    target = MAPPING.get((product_type_ref or "").strip())
    return target.folder_ref if target else None


def refusal(product_type_ref: str | None, product_type: str | None = None) -> str:
    """Почему перенос невозможен — текст админу. Зовётся, когда folder_for() дал None."""
    ref = (product_type_ref or "").strip()
    if not ref:
        return ("у позиции не заполнен вид товара — не могу определить папку снятых, "
                "перенесите вручную")
    if ref in NEEDS_FOLDER:
        return (f"для вида товара «{NEEDS_FOLDER[ref]}» ({ref}) в 1С нет отдельной папки "
                f"снятых — заведите её и добавьте в маппинг, переносить в общую я не буду")
    name = (product_type or "").strip()
    return (f"вид товара {('«' + name + '» ') if name else ''}({ref}) не сопоставлен с "
            f"папкой снятых — перенос не делаю")


def problems(nodes: list[dict]) -> list[str]:
    """Сверка таблицы с деревом `folders` (§19.2.4). Пустой список — можно переносить.

    Проверяем три вещи, и все три означают, что кто-то трогал справочник:
    папки нет вовсе (перенос ушёл бы в никуда), папку переименовали (возможно, её
    назначение сменилось), 1С не считает её папкой снятых.
    """
    by_ref = {str(n.get("ref", "")): n for n in nodes}
    found = []
    for ref, target in MAPPING.items():
        node = by_ref.get(target.folder_ref)
        if node is None:
            found.append(f"{target.product_type}: папки {target.folder_ref} нет в 1С")
            continue
        name = str(node.get("name", ""))
        if target.folder_name and name != target.folder_name:
            found.append(f"{target.product_type}: папка {target.folder_ref} "
                         f"переименована — было «{target.folder_name}», стало «{name}»")
        kind = str(node.get("kind", ""))
        if kind and kind != "discontinued":
            found.append(f"{target.product_type}: 1С считает папку {target.folder_ref} "
                         f"не папкой снятых, а «{kind}»")
    return found

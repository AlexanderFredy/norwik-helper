"""Правила имён номенклатуры (§19.5 спеки).

Пока здесь ТОЛЬКО работа с символами, опасными для XML-выгрузки на сайт: сборка
наименований из частей появится вместе с инструментами правки справочника, когда 1С отдаст
`set-items`. Работа с символами от них не зависит и нужна раньше — ею же проверяются имена,
уже лежащие в 1С.

**Почему это код, а не промпт.** Правило детерминировано, а пропущенный управляющий символ
обнаружится не на разборе прайса, а когда сайт перестанет обновляться — далеко от места
ошибки и не сразу. Такие правила в этом проекте живут в коде (`retail.py`, `scope.py`) и
покрываются тестами.

Запрет действует на то, что уходит в XML: наименование, полное наименование, наименование
для сайта и значение свойства «Коллекция». **В именах папок символы разрешены** — папки на
сайт не идут; функции этого модуля к ним не применяются.

ДВЕ РАЗНЫЕ КАТЕГОРИИ, И ЭТО ГЛАВНОЕ ЗДЕСЬ
------------------------------------------
**Управляющие символы** (`0x00–0x08`, `0x0B`, `0x0C`, `0x0E–0x1F`) в XML недопустимы вообще:
их не спасает никакое экранирование, документ с ними невалиден. Их мы удаляем — безусловно.

**Символы разметки** (`&`, `<`, `>`, `"`, `'`) — законные символы, требующие экранирования.
Их мы НЕ ТРОГАЕМ, и это осознанно: на боевой базе 414 позиций содержат `&`, и это настоящие
имена коллекций — `Onyx&More` у Casa Dolce Casa, `White&Co` у Grespania. Заменить их значило
бы исказить название производителя, а на следующем прогоне агент увидел бы расхождение с
прайсом (§19.6 п.2), которое сам же и создал. Ошибка не в имени товара — ошибка в выгрузке,
которая его не экранирует (§19.5, `ЭкранироватьXML`).

Пока выгрузка не экранирует, `markup_chars()` позволяет предупредить админа — но менять
имена из-за этого нельзя.
"""
from __future__ import annotations

import re

# В XML недопустимы вообще; табуляция, перевод строки и возврат каретки допустимы.
_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")

_SPACES = re.compile(r"\s+")

# Значимые для разметки — требуют экранирования на стороне выгрузки, но НЕ запрещены в имени.
MARKUP = ("&", "<", ">", '"', "'")


def xml_safe(text: str | None) -> str:
    """Имя, пригодное для выгрузки: без управляющих символов и лишних пробелов.

    Символы разметки остаются как есть — их дело экранировать, а не вырезать.
    """
    value = _CONTROL.sub("", text or "")
    return _SPACES.sub(" ", value).strip()


def is_xml_safe(text: str | None) -> bool:
    """Можно ли отдавать имя как есть. Про управляющие символы, не про разметку."""
    return not violations(text)


def violations(text: str | None) -> list[str]:
    """Что делает имя непригодным. Сейчас это только управляющие символы."""
    return ["управляющие символы"] if _CONTROL.search(text or "") else []


def markup_chars(text: str | None) -> list[str]:
    """Символы, которые выгрузка обязана экранировать.

    Не нарушение имени: нужны, чтобы предупредить админа, пока выгрузка на сайт собирает
    XML `ЗаписьТекста` без экранирования. Когда она начнёт экранировать, предупреждение
    станет ненужным, а имена останутся целыми.
    """
    value = text or ""
    return [ch for ch in MARKUP if ch in value]


# --- приведение регистра -------------------------------------------------------------
#
# «Дуб МЕДОВЫЙ» → «Дуб Медовый». Правило общее для всех наименований (§19.5): CAPS LOCK в
# карточке товара это опечатка ввода, а не смысл.
#
# ГРАНИЦА ВЫБРАНА УЗКОЙ, И ЭТО НАМЕРЕННО. Трогаем только КИРИЛЛИЧЕСКИЕ слова от пяти букв:
#
#   * латиница остаётся как есть — там прописные обычно осмысленны: SPC, LVT, EIR, UNILIN,
#     PELI, ANATOLIA, да и артикул AN DSG 901 переписывать нельзя;
#   * короткие кириллические — это аббревиатуры: ПВХ, МДФ, ЛДСП, СПБ. Порог в пять букв
#     оставляет их в покое, отсекая при этом «МЕДОВЫЙ», «АЛЛЮР», «ГЛЯНЕЦ».
#
# Слово со смешанным регистром («ДубМедовый») не трогаем: это не CAPS LOCK, а чей-то
# осознанный стиль, и угадывать в нём границы слов мы не будем.
_CAPS_WORD = re.compile(r"(?<![А-ЯЁа-яё])([А-ЯЁ]{5,})(?![А-ЯЁа-яё])")

# Кириллические аббревиатуры длиннее четырёх букв, которые обязаны остаться прописными.
CAPS_KEEP = frozenset()


def fix_caps(text: str | None) -> str:
    """Слова, набранные CAPS LOCK, приводит к обычному виду. Латиницу не трогает."""
    def one(m: re.Match) -> str:
        word = m.group(1)
        if word in CAPS_KEEP:
            return word
        return word[0] + word[1:].lower()

    return _CAPS_WORD.sub(one, text or "")

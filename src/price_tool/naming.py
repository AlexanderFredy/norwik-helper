"""Правила имён номенклатуры (§19.5 спеки).

Пока здесь ТОЛЬКО очистка от символов, ломающих XML выгрузки на сайт: сборка наименований
из частей появится вместе с инструментами правки справочника, когда 1С отдаст `set-items`.
Очистка от них не зависит и нужна раньше — ею же проверяются имена, уже лежащие в 1С.

**Почему это код, а не промпт.** Замена детерминирована, а пропущенный `&` обнаружится не
на разборе прайса, а когда сайт перестанет обновляться — то есть далеко от места ошибки и
не сразу. Такие правила в этом проекте живут в коде (`retail.py`, `scope.py`, `changes.py`)
и покрываются тестами.

Запрет действует на то, что уходит в XML: наименование, полное наименование, наименование
для сайта и значение свойства «Коллекция». **В именах папок эти символы разрешены** — папки
на сайт не идут; функции этого модуля к ним просто не применяются.
"""
from __future__ import annotations

import re

# Управляющие символы: в XML 1.0 недопустимы ВООБЩЕ, их не спасает экранирование. Все
# прочие запреты — про то, что выгрузка может не экранировать; этот — про то, что документ
# с ними невалиден в принципе. Табуляция, перевод строки и возврат каретки допустимы.
_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")

# Парные прямые кавычки → типографские. Именно парные: одиночная прямая кавычка чаще всего
# обломок, и её мы просто убираем.
_PAIRED_QUOTES = re.compile(r'"([^"]*)"')

# Любой пробельный участок — в один пробел. Табуляция и перевод строки для XML законны, но
# в наименовании товара им делать нечего, а после удаления символов остаются двойные пробелы.
_SPACES = re.compile(r"\s+")

# Апостроф НЕ трогаем: он часть законных названий («L'Antic Colonial»), а в тексте элемента
# XML безобиден. Убирать его значило бы калечить имена ради гипотетической выгрузки с
# одинарными кавычками в атрибутах.
FORBIDDEN = ("&", "<", ">", '"')


def xml_safe(text: str | None) -> str:
    """Имя, пригодное для выгрузки на сайт. Замены детерминированы (§19.5)."""
    value = _CONTROL.sub("", text or "")
    value = _PAIRED_QUOTES.sub(r"«\1»", value)
    value = value.replace("&", " и ").replace('"', "")
    value = value.replace("<", "").replace(">", "")
    return _SPACES.sub(" ", value).strip()


def is_xml_safe(text: str | None) -> bool:
    """Можно ли отдавать это имя как есть."""
    return not violations(text)


def violations(text: str | None) -> list[str]:
    """Какие именно символы мешают — для сообщения админу, а не для решения."""
    value = text or ""
    found = [ch for ch in FORBIDDEN if ch in value]
    if _CONTROL.search(value):
        found.append("управляющие символы")
    return found

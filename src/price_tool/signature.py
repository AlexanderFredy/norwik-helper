"""Сигнатура структуры прайса — ключ запоминаемого маппинга колонок (§6.5.2 спеки).

Считается по «скелету» файла: имена листов + верхние строки с заголовками, БЕЗ данных.
Тот же формат прайса → та же сигнатура → маппинг подхватывается без вопросов админу.

Числа заменяются на «#»: иначе «Прайс с 20.07» и «Прайс с 25.08» дали бы разные сигнатуры,
и маппинг терялся бы каждый месяц — ровно то, ради чего он и заводится.

**«Скелет» — это имена листов и СТРОКА ЗАГОЛОВКОВ КОЛОНОК, и ничего больше** (правка
02.10.2026, см. `_header`). Данные в него попадать не должны ни одной ячейкой: пока он брал
первые непустые строки, в него уезжали контакты менеджера и первые строки товаров, и
сигнатура менялась от прайса к прайсу — вместе с ней терялся не только маппинг, но и
владелец формата со списком листов к разбору.
"""
from __future__ import annotations

import hashlib
import json
import re

from src.price_tool.parser import Sheet

HEAD_ROWS = 8      # сколько текстовых строк берём за «шапку» (только фолбэк по тексту)
HEAD_CELLS = 25    # и сколько ячеек в строке
SCAN_ROWS = 40     # как глубоко ищем шапку, прежде чем сдаться
HEAD_MIN_CELLS = 3  # от скольких текстовых ячеек строка считается заголовком колонок

_DIGITS = re.compile(r"\d+")
_SPACES = re.compile(r"\s+")
_NUMERIC = re.compile(r"^[#\s.,%+\-/×x*()]+$")   # ячейка без букв — это данные, не заголовок


def _norm(cell: str) -> str:
    return _SPACES.sub(" ", _DIGITS.sub("#", cell).strip().lower())


def sheet_key(name: str) -> str:
    """Имя листа в том виде, в каком его видит СИГНАТУРА: числа → «#», регистр снят.

    Нужно там, где имя листа СРАВНИВАЮТ: отметка «разбирать этот лист» хранится именем, а
    поставщик дописывает в имя дату — «Прайс от 20.04.2026» в апреле, «Прайс от 01.10.2026»
    в октябре. Точное сравнение теряло бы отметку админа каждый месяц на том же самом листе
    (бой 02.10.2026), причём теряло бы ТИХО: формат опознан, лист в книге есть, флажок снят.

    Правило намеренно ТО ЖЕ, что у скелета формата: раз сигнатура считает эти два имени
    одним листом, то и выбор листов обязан считать так же — иначе два места расходятся во
    мнении, один ли это лист, и спорить им нечем.
    """
    return _norm(name or "")


def _is_data_row(cells: list[str]) -> bool:
    """Строка с числом (цена, артикул, размер) — данные: они меняются от прайса к прайсу."""
    return any(_NUMERIC.fullmatch(c) for c in cells)


def _header(sheet: Sheet) -> list[str]:
    """Строка заголовков колонок — ОДНА на лист, и в этом весь смысл правки 02.10.2026.

    Раньше в скелет шли первые восемь непустых строк, не похожих на числовые. Но «не
    числовая» ≠ «заголовок»: у Стройиндустрии так попадали блок контактов («+#-#… Лилия»,
    «liliya-g@mail.ru»), пометки брендов и ПЕРВЫЕ СТРОКИ ТОВАРОВ — у них в ячейках буквы
    («ламинат POOL PROMO … Дуб мягкий песочный», «склад», «новинка»). Всё это меняется от
    прайса к прайсу: убрали телефон, сняли пометку «новинка» у двух позиций, добавили
    колонку «цена» к бренду — и сигнатура другая. Формат при этом ТОТ ЖЕ.

    Цена ошибки — не только забытый маппинг колонок: с новой сигнатурой перестаёт
    находиться владелец формата, и агент заводит ВТОРОГО поставщика с именем из имени
    файла, а выбор листов обнуляется (бой 02.10.2026, «Стройиндустрия (Лиля)»).

    Заголовок колонок — это строка из НЕСКОЛЬКИХ текстовых ячеек: «Замок | Размер мм |
    Класс | Фаска | м² в уп | опт/м² | РРЦ/м²». Одноклеточные строки (название фирмы,
    «Прайс-лист», имя бренда) — оформление, оно и дрейфует. Берём ПЕРВУЮ такую строку:
    дальше по листу идут данные, и всё, что было после заголовка, раньше и портило хеш.

    Пусто — законный исход (лист «Остатки склад Краснодар», лист «ИЗМЕНЕНИЯ»): формат
    такого листа описывает его имя, а выдумывать заголовок там, где его нет, незачем.
    """
    for row in sheet.rows[:SCAN_ROWS]:
        cells = [_norm(c) for c in row[:HEAD_CELLS] if c and c.strip()]
        if len(cells) < HEAD_MIN_CELLS or _is_data_row(cells):
            continue
        return cells
    return []


def _skeleton(sheets: list[Sheet]) -> list[dict]:
    """Личность формата: имена листов плюс по строке заголовков на каждый.

    Два поставщика совпадут только при одинаковых именах листов И одинаковых заголовках
    колонок — тогда их маппинг и правда взаимозаменяем, а владельцев формата `find_signatures`
    и так возвращает списком.
    """
    return [{"sheet": _norm(sheet.name), "head": _header(sheet)} for sheet in sheets]


def price_signature(sheets: list[Sheet], text: str | None = None) -> str:
    """Устойчивый ключ формата прайса.

    `text` — фолбэк для файлов без таблиц (pdf): скелет строится по верхним строкам
    извлечённого текста. Без него у pdf-прайсов маппинг не запоминался бы вовсе, а
    неоднозначные колонки как раз и встретились в pdf.
    """
    if sheets:
        raw = json.dumps(_skeleton(sheets), ensure_ascii=False)
    elif text and text.strip():
        head = []
        for line in text.splitlines()[:SCAN_ROWS * 3]:
            cells = [_norm(c) for c in line.split("\t") if c and c.strip()] or \
                    ([_norm(line)] if line.strip() else [])
            if not cells or _is_data_row(cells):
                continue
            head.append(cells[:HEAD_CELLS])
            if len(head) >= HEAD_ROWS * 2:      # у pdf строки короче — берём больше
                break
        raw = json.dumps({"text_head": head}, ensure_ascii=False)
    else:
        return ""
    return hashlib.sha1(raw.encode("utf-8")).hexdigest()[:16]

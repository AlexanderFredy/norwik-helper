# -*- coding: utf-8 -*-
r"""Грубая проверка BSL: баланс блоков и занятые 1С имена.

    .venv\Scripts\python tests/check_bsl.py specs/1c/*.bsl

ЗАЧЕМ. BSL не компилируется ничем, кроме самой 1С, и любая опечатка обходится в круг
выкладки: вставить в конфигурацию, дёрнуть запросом, разобрать ответ. Эта проверка ловит
два класса ошибок, которые стоили таких кругов на деле.

РАЗБОР НАРОЧНО ГРУБЫЙ — регулярками по тексту с вырезанными комментариями и строковыми
литералами. Полноценный разбор BSL здесь не нужен: обе проверки работают на уровне имён и
ключевых слов, а лишняя точность обошлась бы дороже пользы. Ложные срабатывания возможны
(литерал на нескольких строках может сбить вырезание кавычек) — они видны глазом.
"""
import io
import re
import sys

PAIRS = [("Функция", "КонецФункции"), ("Процедура", "КонецПроцедуры"),
         ("Если", "КонецЕсли"), ("Цикл", "КонецЦикла"), ("Попытка", "КонецПопытки")]

# Имена, которые нельзя брать под переменную. Два разных списка по происхождению, но
# последствие одно, поэтому проверяются вместе.
#
# ВСТРОЕННЫЕ ФУНКЦИИ: переменная затеняет функцию, и вызов `Строка(X)` ломается.
FUNCS_RESERVED = {"Строка", "Число", "Дата", "Булево", "Формат", "Тип", "ТипЗнч", "Лев",
                  "Прав", "СтрДлина", "СокрЛП", "Найти"}

# ГЛОБАЛЬНЫЕ КОЛЛЕКЦИИ объектов метаданных: присваивание им падает с «Поле объекта
# недоступно для записи (Имя)». Сообщение называет имя, но не место, и ловится это только
# отладчиком — на `Задачи` так и вышло. Имена выглядят совершенно обычными и в прикладном
# коде напрашиваются сами, поэтому список нужен явный.
COLLECTIONS_RESERVED = {
    "Справочники", "Документы", "ЖурналыДокументов", "Перечисления", "Отчеты",
    "Обработки", "ПланыВидовХарактеристик", "ПланыСчетов", "ПланыВидовРасчета",
    "РегистрыСведений", "РегистрыНакопления", "РегистрыБухгалтерии",
    "РегистрыРасчета", "БизнесПроцессы", "Задачи", "Константы", "Метаданные",
    "ПланыОбмена", "Последовательности", "КритерииОтбора", "ХранилищаНастроек",
    "ВнешниеИсточникиДанных", "Пользователи",
}

BUILTINS = FUNCS_RESERVED | COLLECTIONS_RESERVED


def strip_noise(text):
    """Убрать комментарии и строковые литералы — в них ключевые слова не считаются."""
    out = []
    for line in text.split("\n"):
        # строка запроса начинается с | внутри литерала; литералы вырезаем целиком
        line = re.sub(r'"(?:[^"]|"")*"', '""', line)
        idx = line.find("//")
        if idx >= 0:
            line = line[:idx]
        out.append(line)
    return "\n".join(out)


def check(path):
    raw = io.open(path, encoding="utf-8").read()
    body = strip_noise(raw)
    problems = []

    counts = {}
    for word in [w for pair in PAIRS for w in pair] + ["ИначеЕсли", "Тогда"]:
        counts[word] = len(re.findall(r"(?<![А-Яа-яA-Za-z_])%s(?![А-Яа-яA-Za-z_])" % word,
                                      body))

    # ИначеЕсли НЕ открывает блок и вычитанию не подлежит; лукбехайнд уже не даёт
    # счётчику "Если" поймать хвост слова "ИначеЕсли".
    if counts["Если"] != counts["КонецЕсли"]:
        problems.append("ESLI(%d) != KONECESLI(%d)"
                        % (counts["Если"], counts["КонецЕсли"]))

    for opener, closer in PAIRS:
        if opener in ("Если",):
            continue
        if counts[opener] != counts[closer]:
            problems.append("%s != %s : %d vs %d"
                            % (opener.encode("ascii","replace").decode(), closer.encode("ascii","replace").decode(), counts[opener], counts[closer]))

    # присваивание встроенному имени
    for m in re.finditer(r"^\s*([А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*)\s*=", body,
                         re.M):
        if m.group(1) in BUILTINS:
            line = body[:m.start()].count("\n") + 1
            problems.append("line %d: variable %s is a RESERVED 1C name"
                            % (line, m.group(1)))

    # параметры функций с тем же изъяном
    for m in re.finditer(r"(?:Функция|Процедура)\s+\w+\(([^)]*)\)", body):
        for part in m.group(1).split(","):
            name = part.strip().split("=")[0].strip().replace("Знач ", "")
            if name in BUILTINS:
                problems.append("param %s is a RESERVED 1C name" % name)

    return problems


bad = 0
for path in sys.argv[1:]:
    issues = check(path)
    name = path.split("\\")[-1].split("/")[-1]
    if issues:
        bad = 1
        print("%s:" % name)
        for issue in issues:
            print("   x %s" % issue)
    else:
        print("%s: structure balanced" % name)

sys.exit(bad)
